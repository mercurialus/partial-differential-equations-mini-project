"""results/results.json -> report/results.tex, a list of \\newcommand macros.

Every number quoted in the report and slides comes from here. Scalars are
wrapped in \\num{} (siunitx) so 1.2e-05 prints as 1.2 x 10^-5. Table bodies are
exported as whole macros (\\TableMethodsRows etc.).

    python scripts/export_macros.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "results" / "results.json").read_text())
WORDS = {80: "Eighty", 90: "Ninety", 100: "Hundred", 110: "HundredTen", 120: "HundredTwenty",
         85: "EightyFive", 125: "HundredTwentyFive"}


def sig(x, n=3):
    """n significant figures, scientific notation for very small/large values."""
    if x == float("inf") or x != x:
        return r"\infty"
    if x == 0:
        return "0"
    if float(x).is_integer() and abs(x) < 1e7:
        return str(int(x))
    if 1e-3 <= abs(x) < 1e5:
        s = f"{x:.{n}g}"
        return s
    m, e = f"{x:.{n - 1}e}".split("e")
    return f"{m}e{int(e)}"


def num(x, n=3):
    s = sig(x, n)
    return s if s == r"\infty" else rf"\num{{{s}}}"


def fixed(x, d=4):
    return rf"\num{{{x:.{d}f}}}"


lines = ["% Auto-generated by scripts/export_macros.py from results/results.json. Do not edit."]


def m(name, value):
    lines.append(rf"\newcommand{{\{name}}}{{{value}}}")


# --- parameters ---------------------------------------------------------------
p = R["params"]
m("Kval", num(p["K"])); m("rval", num(p["r"])); m("sigmaval", num(p["sigma"])); m("Tval", num(p["T"]))
m("Bone", num(p["B1"])); m("Btwo", num(p["B2"]))
m("kval", num(p["k"])); m("alphaval", num(p["alpha"])); m("betaval", num(p["beta"]))
m("taufinal", num(p["tau_final"], 4))

# --- exp 1: method comparison -------------------------------------------------------
e1 = R["exp1"]
rows = []
for q in e1["rows"]:
    rows.append(rf"{q['S']:.0f} & {fixed(q['formula'])} & {fixed(q['heat_kernel'])} & "
                rf"{fixed(q['explicit'])} & {fixed(q['cn'])} & {fixed(q['mc'], 3)} & "
                rf"[{fixed(q['mc_lo'], 3)}, {fixed(q['mc_hi'], 3)}] \\")
    m("price" + WORDS[int(q["S"])], fixed(q["formula"]))
m("TableMethodsRows", "\n".join(rows))
m("errHeatKernel", num(e1["max_err"]["heat_kernel"], 2))
m("errExplicit", num(e1["max_err"]["explicit"], 2))
m("errCN", num(e1["max_err"]["cn"], 2))
m("errMC", num(e1["max_err"]["mc"], 2))
m("mcCoverCount", str(sum(q["mc_covers"] for q in e1["rows"])))
m("mcSeMax", num(max(q["mc_se"] for q in e1["rows"]), 2))
m("fdDx", num(e1["settings"]["dx"])); m("fdLam", num(e1["settings"]["lam"]))
m("cnSteps", num(e1["settings"]["cn_steps"])); m("mcPaths", r"\num{1e6}")
m("parityGap", num(e1["parity_max_gap"], 2))

# --- exp 2: stability -------------------------------------------------------------
e2 = R["exp2"]
m("stabDx", num(e2["dx"]))
rows = []
for q in e2["rows"]:
    rows.append(rf"{q['lam']:g} & {fixed(q['lam_eff'])} & {q['n_steps']} & {num(q['G_max'], 3)} & "
                rf"{num(q['max_err'], 2)} \\")
    m("stabErr" + {0.3: "Thirty", 0.4: "Forty", 0.5: "Half", 0.52: "FiftyTwo", 0.55: "FiftyFive",
                   0.6: "Sixty"}[q["lam"]], num(q["max_err"], 2))
m("TableStabilityRows", "\n".join(rows))

# --- exp 3: convergence -------------------------------------------------------------
e3 = R["exp3"]
m("convOrderMax", f"{e3['order_max']:.2f}")
m("convOrderK", f"{e3['order_at_K']:.2f}")
m("convLocalMin", f"{min(e3['local_orders']):.3f}")
m("convLocalMax", f"{max(e3['local_orders']):.3f}")
rows = [rf"{num(q['dx'], 5)} & {q['n_steps']} & {num(q['max_err'], 3)} & {num(q['err_at_K'], 3)} \\"
        for q in e3["rows"]]
m("TableConvergenceRows", "\n".join(rows))
m("convErrFinest", num(e3["rows"][-1]["max_err"], 2))
if "offnode" in e3:
    m("convOrderOff", f"{e3['offnode']['order']:.2f}")
    m("convLocalOffMin", f"{min(e3['offnode']['local_orders']):.2f}")
    m("convLocalOffMax", f"{max(e3['offnode']['local_orders']):.2f}")
    m("convErrOffFinest", num(e3["offnode"]["max_err"][-1], 2))

# --- exp 5: barrier ---------------------------------------------------------------------
e5 = R["exp5"]
m("barA", fixed(e5["a"])); m("barB", fixed(e5["b"])); m("barEll", fixed(e5["ell"]))
m("barDiffMax", num(max(q["max_diff"] for q in e5["comparison"]), 2))
rows = [rf"{q['S']:.0f} & {fixed(q['barrier'])} & {fixed(q['vanilla'])} \\" for q in e5["prices"]]
m("TableBarrierRows", "\n".join(rows))
m("barPriceHundred", fixed([q for q in e5["prices"] if q["S"] == 100][0]["barrier"]))
tn = e5["terms_needed"]
m("termsShortest", str(tn[0]["N"])); m("termsLongest", str(tn[-1]["N"]))
m("termsShortestDays", f"{tn[0]['tau'] * 365:.0f}")
import math
pred = lambda ty: e5["ell"] / math.pi * math.sqrt(math.log(1 / e5["tol"]) / (0.5 * R["params"]["sigma"] ** 2 * ty))
m("termsPredShortest", f"{pred(tn[0]['tau']):.0f}")
m("termsPredLongest", f"{pred(tn[-1]['tau']):.1f}")

# --- exp 6: neural networks ---------------------------------------------------------------
if "exp6" in R:
    e6 = R["exp6"]
    rows, short = [], []
    get = lambda N, kind: [q for q in e6["summary"] if q["N"] == N and q["kind"] == kind][0]
    for N in (20, 50, 200):
        a, b = get(N, "plain"), get(N, "pinn")
        rows.append(rf"{N} & {num(a['rmse_mean'], 2)} $\pm$ {num(a['rmse_std'], 1)} & "
                    rf"{num(b['rmse_mean'], 2)} $\pm$ {num(b['rmse_std'], 1)} & "
                    rf"{num(a['res_mean'], 2)} & {num(b['res_mean'], 2)} \\")
        short.append(rf"{N} & {num(a['rmse_mean'], 2)} & {num(b['rmse_mean'], 2)} & "
                     rf"{num(a['res_mean'], 2)} & {num(b['res_mean'], 2)} \\")
        w = {20: "Twenty", 50: "Fifty", 200: "TwoHundred"}[N]
        m("nnPlainRmse" + w, num(a["rmse_mean"], 2)); m("nnPinnRmse" + w, num(b["rmse_mean"], 2))
        m("nnPlainRes" + w, num(a["res_mean"], 2)); m("nnPinnRes" + w, num(b["res_mean"], 2))
        m("nnRmseRatio" + w, f"{a['rmse_mean'] / b['rmse_mean']:.0f}")
        m("nnResRatio" + w, f"{a['res_mean'] / b['res_mean']:.0f}")
        m("nnPinnSeconds" + w, f"{b['seconds_mean']:.0f}")
    m("TableNNRows", "\n".join(rows))
    m("TableNNRowsShort", "\n".join(short))
    c = e6["config"]
    m("nnAdamIters", num(c["adam_iters"])); m("nnLbfgsIters", num(c["lbfgs_iters"]))
    m("nnColloc", num(c["n_colloc"])); m("nnTerminal", num(c["n_terminal"]))
    m("nnBoundary", num(c["n_boundary"])); m("nnSeeds", str(len(e6["seeds"])))
    m("nnWidth", str(c["width"])); m("nnDepth", str(c["depth"])); m("nnLr", num(c["lr"]))
    m("nnSmax", num(c["s_max"])); m("nnThetaMin", num(c["theta_min_test"]))
    m("nnTestGrid", str(c["n_test"]))

# --- exp 7: ill-posedness ------------------------------------------------------------------
e7 = R["exp7"]
m("illEps", num(e7["eps"])); m("illModes", str(e7["n_modes"]))
by_t = {q["t"]: q for q in e7["rows"]}
m("illMaxNoisyHalfMilli", num(by_t[0.0005]["max_noisy"], 2))
m("illMaxNoisyOneMilli", num(by_t[0.001]["max_noisy"], 2))
m("illMaxNoisyTwoMilli", num(by_t[0.002]["max_noisy"], 2))
m("illAmpOneMilli", num(by_t[0.001]["amp_top"], 2))
m("illMaxCleanThreeMilli", num(by_t[0.003]["max_clean"], 2))
h = e7["hadamard"]
m("hadTwentyData", num(h["data_size"][-1])); m("hadTwentySol", num(h["sol_at_t"][-1], 2))

out = ROOT / "report" / "results.tex"
out.write_text("\n".join(lines) + "\n")
(ROOT / "slides" / "results.tex").write_text("\n".join(lines) + "\n")
print(f"wrote {out.relative_to(ROOT)} and slides/results.tex ({len(lines) - 1} macros)")
